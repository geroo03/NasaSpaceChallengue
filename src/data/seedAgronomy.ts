function buildClimateSeries(
  rainProfile: number[],
  etoProfile: number[],
  moistureProfile: number[],
  ndviProfile: number[],
) {
  return CAMPAIGN_MONTHS.map((monthLabel, monthIndex) => ({
    monthIndex,
    monthLabel,
    precipitationMm: rainProfile[monthIndex],
    etoMm: etoProfile[monthIndex],
    soilMoistureMm: moistureProfile[monthIndex],
    ndvi: ndviProfile[monthIndex],
  }));
}

